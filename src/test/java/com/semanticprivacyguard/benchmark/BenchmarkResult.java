package com.semanticprivacyguard.benchmark;

import com.semanticprivacyguard.SemanticPrivacyGuard;
import com.semanticprivacyguard.model.PIIMatch;
import com.semanticprivacyguard.model.PIIType;

import java.lang.management.ManagementFactory;
import java.lang.management.MemoryMXBean;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

/**
 * Immutable aggregate result for one benchmark configuration.
 *
 * <p>Created via the static factory {@link #compute(String, List, SemanticPrivacyGuard)},
 * which runs the full labeled dataset through the supplied {@link SemanticPrivacyGuard}
 * instance, computes per-type confusion matrices, and derives macro-averaged
 * precision / recall / F1 plus throughput and heap telemetry.</p>
 *
 * <h2>Overlap-based matching</h2>
 * <p>A detection is counted as a TP for a labeled span when the detection's
 * character interval overlaps the span's interval <em>and</em> the types match.
 * This avoids penalising detectors that return slightly wider or narrower spans
 * than the reference annotation.</p>
 *
 * @param configName      human-readable name for this configuration
 * @param perType         per-{@link PIIType} confusion matrix
 * @param macroPrecision  macro-averaged precision across types in the dataset
 * @param macroRecall     macro-averaged recall across types in the dataset
 * @param macroF1         macro-averaged F1 across types in the dataset
 * @param throughputMbps  throughput in megabytes per second (2 bytes/char)
 * @param peakHeapMb      peak heap usage in megabytes observed during the run
 * @param timingMs        total wall-clock time of the analysis phase in milliseconds
 */
public record BenchmarkResult(
        String configName,
        Map<PIIType, TypeMetrics> perType,
        double macroPrecision,
        double macroRecall,
        double macroF1,
        double throughputMbps,
        long peakHeapMb,
        long timingMs) {

    /** Bytes per Java {@code char} (UTF-16). Used for throughput calculation. */
    private static final long BYTES_PER_CHAR = 2L;

    /** Bytes in one megabyte. */
    private static final long BYTES_PER_MB = 1_048_576L;

    // ── Static factory ────────────────────────────────────────────────────────

    /**
     * Runs {@code dataset} through {@code spg} and builds a {@code BenchmarkResult}.
     *
     * <ol>
     *   <li>GC is requested and baseline heap is sampled before the analysis loop.</li>
     *   <li>Each sample is analysed; detections are matched to labeled spans by
     *       type + overlap.</li>
     *   <li>TP/FP/FN are accumulated per type into {@link TypeMetrics}.</li>
     *   <li>Macro metrics are averaged over types that appear in the dataset.</li>
     *   <li>Throughput is calculated from total characters processed and wall
     *       time, converted to MB/s assuming 2 bytes per Java char.</li>
     * </ol>
     *
     * @param configName human-readable label for this configuration
     * @param dataset    labeled samples generated by {@link SyntheticDataset}
     * @param spg        the {@link SemanticPrivacyGuard} instance to benchmark
     * @return a fully populated {@code BenchmarkResult}
     */
    public static BenchmarkResult compute(String configName,
                                          List<LabeledSample> dataset,
                                          SemanticPrivacyGuard spg) {
        // ── 1. Pre-run setup ──────────────────────────────────────────────────
        System.gc();
        MemoryMXBean memBean = ManagementFactory.getMemoryMXBean();
        long heapBefore = memBean.getHeapMemoryUsage().getUsed();

        // Accumulators: tp[type], fp[type], fn[type]
        Map<PIIType, int[]> tpMap = new EnumMap<>(PIIType.class);
        Map<PIIType, int[]> fpMap = new EnumMap<>(PIIType.class);
        Map<PIIType, int[]> fnMap = new EnumMap<>(PIIType.class);

        // Track which types appear in the reference data
        for (LabeledSample sample : dataset) {
            for (LabeledSpan span : sample.spans()) {
                tpMap.computeIfAbsent(span.type(), k -> new int[1]);
                fpMap.computeIfAbsent(span.type(), k -> new int[1]);
                fnMap.computeIfAbsent(span.type(), k -> new int[1]);
            }
        }

        long totalChars = 0L;

        // ── 2. Analysis loop ──────────────────────────────────────────────────
        long startMs = System.currentTimeMillis();

        for (LabeledSample sample : dataset) {
            String text = sample.text();
            totalChars += text.length();

            List<PIIMatch> detections = spg.analyse(text);

            // For each labeled span: does any detection of the same type overlap?
            for (LabeledSpan span : sample.spans()) {
                boolean matched = false;
                for (PIIMatch det : detections) {
                    if (det.getType() == span.type()
                            && span.overlaps(det.getStartIndex(), det.getEndIndex())) {
                        matched = true;
                        break;
                    }
                }
                if (matched) {
                    tpMap.computeIfAbsent(span.type(), k -> new int[1])[0]++;
                } else {
                    fnMap.computeIfAbsent(span.type(), k -> new int[1])[0]++;
                }
            }

            // For each detection: is there any labeled span of the same type that overlaps?
            for (PIIMatch det : detections) {
                boolean supported = false;
                for (LabeledSpan span : sample.spans()) {
                    if (span.type() == det.getType()
                            && span.overlaps(det.getStartIndex(), det.getEndIndex())) {
                        supported = true;
                        break;
                    }
                }
                if (!supported) {
                    // This detection has no ground-truth backing — it's a false positive.
                    // Register the type in all maps (it may not appear in the reference data).
                    fpMap.computeIfAbsent(det.getType(), k -> new int[1])[0]++;
                    tpMap.computeIfAbsent(det.getType(), k -> new int[1]);
                    fnMap.computeIfAbsent(det.getType(), k -> new int[1]);
                }
            }
        }

        long timingMs = System.currentTimeMillis() - startMs;

        // ── 3. Peak heap ──────────────────────────────────────────────────────
        long heapAfter  = memBean.getHeapMemoryUsage().getUsed();
        long peakHeapMb = Math.max(0, heapAfter - heapBefore) / BYTES_PER_MB;

        // ── 4. Assemble per-type metrics ──────────────────────────────────────
        Map<PIIType, TypeMetrics> perType = new EnumMap<>(PIIType.class);
        for (PIIType type : tpMap.keySet()) {
            int tp = tpMap.getOrDefault(type, new int[1])[0];
            int fp = fpMap.getOrDefault(type, new int[1])[0];
            int fn = fnMap.getOrDefault(type, new int[1])[0];
            perType.put(type, new TypeMetrics(type, tp, fp, fn));
        }

        // ── 5. Macro averages (only over types in the reference dataset) ──────
        // We average over types that have at least one labeled span (tp+fn > 0).
        double sumP = 0, sumR = 0, sumF1 = 0;
        int typeCount = 0;
        for (Map.Entry<PIIType, TypeMetrics> e : perType.entrySet()) {
            TypeMetrics m = e.getValue();
            if (m.tp() + m.fn() > 0) { // type has ground-truth positives
                sumP   += m.precision();
                sumR   += m.recall();
                sumF1  += m.f1();
                typeCount++;
            }
        }
        double macroPrecision = typeCount > 0 ? sumP  / typeCount : 1.0;
        double macroRecall    = typeCount > 0 ? sumR  / typeCount : 1.0;
        double macroF1        = typeCount > 0 ? sumF1 / typeCount : 1.0;

        // ── 6. Throughput: (chars * 2 bytes) / (timingMs / 1000) / 1_000_000 ─
        double timingSec    = timingMs > 0 ? timingMs / 1_000.0 : 0.001; // avoid /0
        double totalBytes   = totalChars * BYTES_PER_CHAR;
        double throughputMbps = (totalBytes / BYTES_PER_MB) / timingSec;

        return new BenchmarkResult(
                configName,
                Map.copyOf(perType),
                macroPrecision,
                macroRecall,
                macroF1,
                throughputMbps,
                peakHeapMb,
                timingMs);
    }
}
